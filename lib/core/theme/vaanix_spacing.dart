/// VaaniX V1 Design System — Spacing Tokens
///
/// 4px-grid spacing scale for layout rhythm, padding, and element separation.
library;

abstract final class VaaniXSpacing {
  /// 4px — hairline gaps, icon-to-label inside chips
  static const double xs = 4.0;

  /// 8px — tight internal padding, badge gaps
  static const double sm = 8.0;

  /// 12px — related element separation
  static const double md = 12.0;

  /// 16px — standard container padding, card insets
  static const double lg = 16.0;

  /// 20px — generous card padding
  static const double cardPadding = 20.0;

  /// 24px — section separation
  static const double xl = 24.0;

  /// 32px — large section separation
  static const double xxl = 32.0;

  /// 40px — hero block separation
  static const double xxxl = 40.0;

  /// Standard screen horizontal margin (16-20px)
  static const double screenMargin = 16.0;

  /// Standard screen horizontal margin wide
  static const double screenMarginWide = 20.0;
}
